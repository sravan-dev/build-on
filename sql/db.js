#!/usr/bin/env node
/**
 * First-run bootstrap for Buildon Accounts.
 *
 *   node sql/db.js
 *
 * On the very first run this:
 *   1. writes a .env file (production database settings) if one does not exist;
 *   2. creates the database if it is missing;
 *   3. imports sql/buildon_qatar.sql into it, but only when the database is
 *      still empty — an existing installation is never overwritten.
 *
 * Re-running it is safe: each step is skipped once it has been done.
 *
 * Credentials are NOT hardcoded in this file, because this repository is
 * public. Supply them once, by either:
 *
 *   a) copying sql/db.config.example.json to sql/db.config.json and filling it
 *      in (that file is gitignored), or
 *   b) exporting the values in the environment before running:
 *
 *        PROD_DB_NAME=... PROD_DB_USER=... PROD_DB_PASS=... node sql/db.js
 *
 * Anything not supplied falls back to the defaults below.
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const ENV_PATH = path.join(ROOT, '.env');
const SQL_PATH = path.join(__dirname, 'buildon_qatar.sql');
const CONFIG_PATH = path.join(__dirname, 'db.config.json');

// Non-secret defaults. Host/port/name match the production server.
const DEFAULTS = {
  PROD_DB_TYPE: 'mysql',
  PROD_DB_HOST: 'localhost',
  PROD_DB_PORT: '3306',
  PROD_DB_NAME: 'buildon_qatar',
  PROD_DB_USER: 'buildon_qatar',
  PROD_DB_PASS: '',
};

function loadConfig() {
  let fromFile = {};
  if (fs.existsSync(CONFIG_PATH)) {
    try {
      fromFile = JSON.parse(fs.readFileSync(CONFIG_PATH, 'utf8'));
    } catch (err) {
      fail('sql/db.config.json is not valid JSON: ' + err.message);
    }
  }

  const config = {};
  for (const key of Object.keys(DEFAULTS)) {
    // Environment wins, then the local config file, then the default.
    config[key] = process.env[key] || fromFile[key] || DEFAULTS[key];
  }
  return config;
}

function fail(message) {
  console.error('\n  ✗ ' + message + '\n');
  process.exit(1);
}

function info(message) {
  console.log('  · ' + message);
}

function done(message) {
  console.log('  ✓ ' + message);
}

/** Locate the mysql client: PATH, then the usual XAMPP/MySQL install spots. */
function findMysqlClient() {
  const candidates = [
    process.env.MYSQL_CLIENT,
    'mysql',
    'C:/xampp/mysql/bin/mysql.exe',
    'E:/xampp/mysql/bin/mysql.exe',
    '/usr/bin/mysql',
    '/usr/local/bin/mysql',
  ].filter(Boolean);

  for (const candidate of candidates) {
    const probe = spawnSync(candidate, ['--version'], { encoding: 'utf8' });
    if (!probe.error && probe.status === 0) {
      return candidate;
    }
  }
  return null;
}

function mysqlArgs(config, extra) {
  const args = [
    '--host=' + config.PROD_DB_HOST,
    '--port=' + config.PROD_DB_PORT,
    '--user=' + config.PROD_DB_USER,
    '--default-character-set=utf8mb4',
  ];
  if (config.PROD_DB_PASS !== '') {
    args.push('--password=' + config.PROD_DB_PASS);
  }
  return args.concat(extra);
}

function runMysql(client, config, extra, options) {
  const result = spawnSync(client, mysqlArgs(config, extra), Object.assign({ encoding: 'utf8' }, options || {}));
  if (result.error) {
    fail('Could not run the mysql client: ' + result.error.message);
  }
  return result;
}

/** Step 1 — write .env, preserving any existing one. */
function writeEnv(config) {
  if (fs.existsSync(ENV_PATH)) {
    info('.env already exists — left untouched');
    return;
  }

  const examplePath = path.join(ROOT, '.env.example');
  let contents;

  if (fs.existsSync(examplePath)) {
    // Start from the template so every non-database setting is present too.
    contents = fs.readFileSync(examplePath, 'utf8');
    for (const [key, value] of Object.entries(config)) {
      const line = key + '=' + value;
      const pattern = new RegExp('^' + key + '=.*$', 'm');
      contents = pattern.test(contents) ? contents.replace(pattern, line) : contents + '\n' + line;
    }
    if (/^APP_ENV=.*$/m.test(contents)) {
      contents = contents.replace(/^APP_ENV=.*$/m, 'APP_ENV=production');
    }
  } else {
    contents = [
      '# Generated by sql/db.js on first run.',
      'APP_ENV=production',
      '',
      '# Production database',
      'PROD_DB_TYPE=' + config.PROD_DB_TYPE,
      'PROD_DB_HOST=' + config.PROD_DB_HOST,
      'PROD_DB_PORT=' + config.PROD_DB_PORT,
      'PROD_DB_NAME=' + config.PROD_DB_NAME,
      'PROD_DB_USER=' + config.PROD_DB_USER,
      'PROD_DB_PASS=' + config.PROD_DB_PASS,
      '',
    ].join('\n');
  }

  fs.writeFileSync(ENV_PATH, contents, { encoding: 'utf8' });
  done('.env created (APP_ENV=production, database ' + config.PROD_DB_NAME + ')');
}

/** Step 2 — create the database if it is absent. */
function ensureDatabase(client, config) {
  const sql = 'CREATE DATABASE IF NOT EXISTS `' + config.PROD_DB_NAME +
    '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;';
  const result = runMysql(client, config, ['--execute=' + sql]);

  if (result.status !== 0) {
    fail('Could not create the database:\n' + (result.stderr || '').trim());
  }
  done('database `' + config.PROD_DB_NAME + '` is present');
}

/** Step 3 — import the dump, but only into an empty database. */
function importDump(client, config) {
  if (!fs.existsSync(SQL_PATH)) {
    fail('Missing ' + path.relative(ROOT, SQL_PATH) + ' — cannot import.');
  }

  const countSql = "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = '" +
    config.PROD_DB_NAME + "';";
  const probe = runMysql(client, config, ['--batch', '--skip-column-names', '--execute=' + countSql]);

  if (probe.status !== 0) {
    fail('Could not inspect the database:\n' + (probe.stderr || '').trim());
  }

  const tableCount = parseInt((probe.stdout || '0').trim(), 10) || 0;
  if (tableCount > 0) {
    info('database already has ' + tableCount + ' tables — import skipped');
    return;
  }

  info('importing ' + path.basename(SQL_PATH) + ' ...');
  const result = runMysql(client, config, [config.PROD_DB_NAME], {
    input: fs.readFileSync(SQL_PATH, 'utf8'),
  });

  if (result.status !== 0) {
    fail('Import failed:\n' + (result.stderr || '').trim());
  }
  done('database imported');
}

function main() {
  console.log('\nBuildon Accounts — first-run setup\n');

  const config = loadConfig();

  if (!config.PROD_DB_PASS) {
    console.warn('  ! No database password supplied. Set PROD_DB_PASS in the environment,');
    console.warn('    or copy sql/db.config.example.json to sql/db.config.json and fill it in.');
    console.warn('    Continuing with an empty password.\n');
  }

  writeEnv(config);

  const client = findMysqlClient();
  if (!client) {
    console.warn('\n  ! No mysql client found on PATH, so the database step was skipped.');
    console.warn('    Import it manually:');
    console.warn('      mysql -u ' + config.PROD_DB_USER + ' -p ' + config.PROD_DB_NAME +
      ' < sql/buildon_qatar.sql\n');
    return;
  }

  ensureDatabase(client, config);
  importDump(client, config);

  console.log('\nSetup complete. Serve the project root with PHP 8 and open index.php.\n');
}

main();
